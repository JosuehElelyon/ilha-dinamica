const { contextBridge, ipcRenderer } = require('electron');

const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, d) => cb(d));

contextBridge.exposeInMainWorld('api', {
  setInteractive: (v) => ipcRenderer.send('interactive', v),
  copy: (t) => ipcRenderer.send('copy', t),
  clearClips: () => ipcRenderer.send('clear-clips'),
  mediaCmd: (c) => ipcRenderer.send('media-cmd', c),
  setVol: (v) => ipcRenderer.send('set-vol', v),
  toggleMute: () => ipcRenderer.send('toggle-mute'),
  setBright: (v) => ipcRenderer.send('set-bright', v),
  setMic: (v) => ipcRenderer.send('set-mic', v),
  toggleMic: () => ipcRenderer.send('toggle-mic'),
  setDevice: (id) => ipcRenderer.send('set-device', id),
  refreshDevices: () => ipcRenderer.send('refresh-devices'),
  runAction: (a) => ipcRenderer.send('run-action', a),
  pickPath: (kind) => ipcRenderer.invoke('pick-path', kind),
  getData: () => ipcRenderer.invoke('get-data'),
  saveNotes: (t) => ipcRenderer.send('save-notes', t),
  saveReminders: (r) => ipcRenderer.send('save-reminders', r),
  saveSetting: (key, value) => ipcRenderer.send('save-setting', { key, value }),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  setLogin: (v) => ipcRenderer.send('set-login', v),
  quit: () => ipcRenderer.send('quit'),
  cleanScan: () => ipcRenderer.invoke('clean-scan'),
  cleanRun: (keys) => ipcRenderer.invoke('clean-run', keys),
  trimRam: () => ipcRenderer.invoke('trim-ram'),
  flushDns: () => ipcRenderer.invoke('flush-dns'),
  refreshProcs: () => ipcRenderer.send('procs-refresh'),
  kill: (o) => ipcRenderer.invoke('kill', o),
  relaunchAdmin: () => ipcRenderer.send('relaunch-admin'),
  onClips: on('clips'),
  onMedia: on('media'),
  onSys: on('sys'),
  onVol: on('vol'),
  onBright: on('bright'),
  onDevices: on('devices'),
  onProcs: on('procs'),
  onToggle: on('toggle')
});
